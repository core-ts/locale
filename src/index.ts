export function binarySearchByCode<T extends { code: string }>(items: readonly T[], code: string): T | undefined {
  let left = 0
  let right = items.length - 1

  while (left <= right) {
    const mid = left + ((right - left) >> 1)
    const item = items[mid]

    if (item.code === code) {
      return item
    }

    if (item.code < code) {
      left = mid + 1
    } else {
      right = mid - 1
    }
  }

  return undefined
}

