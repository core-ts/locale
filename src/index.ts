export function getCurrency(code: string): Currency | undefined {
  return binarySearchByCode(currencies, code)
}
export function getCurrencyDecimalDigits(currencyCode?: string): number {
  if (!currencyCode) {
    return resources.defaultCurrency.decimalDigits
  }
  const currency = getCurrency(currencyCode)
  if (currency) {
    return currency.decimalDigits
  }
  return resources.defaultCurrency.decimalDigits
}
export interface StringMap {
  [key: string]: string
}
export function getLocale(lang?: string | null): Locale | undefined {
  if (!lang) {
    return undefined
  }
  if (lang.length === 2 || lang.length === 3) {
    const code = langMap[lang]
    if (!code) {
      return undefined
    }
    return binarySearchByCode(locales, code)
  } else {
    return binarySearchByCode(locales, lang)
  }
}
export function getLocaleCode(lang: string): string | undefined {
  const i = langMap[lang]
  return i
}
export function getDateFormat(lang: string): string {
  const locale = getLocale(lang)
  if (locale) {
    return locale.dateFormat
  }
  return resources.defaultLocale.dateFormat
}
